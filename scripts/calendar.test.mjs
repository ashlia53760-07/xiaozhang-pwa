import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
const folder = new URL("../.local-review/calendar-tests/modules/", import.meta.url);
await mkdir(folder, { recursive: true });
for (const name of ["calendar", "calendar-data", "calendar-observances", "solar-term-data"]) {
  const code = ts.transpileModule(await readFile(new URL(`../src/${name}.ts`, import.meta.url), "utf8"), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText.replace(/from "\.\/([^".]+)"/g, 'from "./$1.mjs"');
  await writeFile(new URL(`${name}.mjs`, folder), code);
}
const c = await import(new URL("calendar.mjs", folder)), { birthdaySources } = await import(new URL("calendar-data.mjs", folder));
for (const date of ["2026-02-29", "2026-04-31", "2026-13-01", "2026-00-02", "no date"]) assert.equal(c.validDay(date), false, date);
assert.equal(c.validDay("2028-02-29"), true);
assert.equal(c.validBirthday({ month: 2, day: 29 }), true);
assert.equal(c.validBirthday({ month: 2, day: 30 }), false);
assert.equal(c.addDays("2026-12-31", 1), "2027-01-01");
assert.equal(c.addDays("2028-03-01", -1), "2028-02-29");
for (let year = 2000; year <= 2040; year++) for (let m = 1; m <= 12; m++) {
  const month = `${year}-${String(m).padStart(2, "0")}`, days = c.monthDays(month);
  assert.equal(days.length, 42); assert.equal(c.dateValue(days[0]).getDay(), 1);
  assert(days.includes(`${month}-01`)); assert.equal(new Set(days).size, 42);
}
assert.equal(c.lunarInfo("2026-02-17").festival, "春节");
assert.equal(c.lunarInfo("2026-02-16").festival, "除夕");
assert.equal(c.lunarInfo("2026-06-19").festival, "端午节");
assert.equal(c.lunarInfo("2026-09-25").festival, "中秋节");
assert.equal(c.dayLabels("2026-02-14", c.emptyCalendar()).holiday.isOffDay, false);
assert.equal(c.dayLabels("2026-02-15", c.emptyCalendar()).holiday.isOffDay, true);
assert.equal(c.dayLabels("2027-02-14", c.emptyCalendar()).holiday, undefined);
assert.equal(Object.keys(birthdaySources).length, 16);
assert.equal(c.moodLabel("开心"), "🥰 开心");
assert.equal(c.moodLabel("平静"), "😌 平静");
assert.equal(c.moodLabel("未收录心情"), "未收录心情");
assert.equal(c.moodLabel("constructor"), "constructor");
assert.deepEqual(c.contactBirthday("wu-xie", { contacts: {} }), { month: 3, day: 5 });
assert.deepEqual(c.contactBirthday("wu-xie", { contacts: { "wu-xie": { month: 1, day: 1 } } }), { month: 1, day: 1 });
assert.equal(c.contactBirthday("zhang-qiling", { contacts: {} }), undefined);
const diary = { id: "legacy", createdAt: +new Date(2026, 0, 2, 21), updatedAt: +new Date(2026, 1, 20), content: "旧记录" };
assert.equal(c.diaryDay(diary), "2026-01-02");
assert.equal(c.diaryDay({ ...diary, automationKey: "diary:2025-12-31" }), "2025-12-31");
assert.equal(c.diaryDay({ ...diary, date: "2026-03-05" }), "2026-03-05");
const data = c.emptyCalendar();
data.records["2026-11-03"] = { date: "2026-11-03", mood: "难过", period: "start", note: "想喝热水", updatedAt: 1 };
data.records["2026-10-26"] = { date: "2026-10-26", note: "过期的秘密", updatedAt: 1 };
data.records["2026-11-04"] = { date: "2026-11-04", note: "未来的秘密", updatedAt: 1 };
assert(c.validCalendar(data));
const prompt = c.calendarContext(data, [{ ...diary, date: "2026-11-02", content: "昨天有点累" }], new Date(2026, 10, 3));
assert.match(prompt, /经期开始/); assert.match(prompt, /想喝热水/); assert.match(prompt, /昨天有点累/);
assert.doesNotMatch(prompt, /过期的秘密|未来的秘密/);
assert.equal(c.calendarContext({ ...data, shareWithChat: false }, [], new Date(2026, 10, 3)), "");
assert(!c.validCalendar({ ...data, records: { "2026-02-30": { ...data.records["2026-11-03"], date: "2026-02-30" } } }));
assert(!c.validCalendar({ ...data, records: { "2026-11-03": { ...data.records["2026-11-03"], period: "constructor" } } }));
const ics = `BEGIN:VCALENDAR\r\nVERSION:2.0\r\nBEGIN:VEVENT\r\nUID:test-1\r\nDTSTART;VALUE=DATE:20261231\r\nDTEND;VALUE=DATE:20270102\r\nSUMMARY:跨年\\,一起\r\nRRULE:FREQ=YEARLY\r\nEND:VEVENT\r\nBEGIN:VEVENT\r\nDTSTART:20261103T090000Z\r\nSUMMARY:有时间\r\nEND:VEVENT\r\nEND:VCALENDAR`;
